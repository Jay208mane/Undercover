export function getWordPairById(id: number): WordPair {
  const pair = wordPairs.find((candidate) => candidate.id === id);
  if (!pair) throw new Error(`Unknown word-pair ID ${id}.`);
  return pair;
}

export function createWordPairDeck(
  category = 'random',
  random: () => number = Math.random
): number[] {
  const legacyCategories: Record<string, string> = {
    food: 'food-drinks',
    animals: 'animals-birds',
    places: 'countries-places',
    objects: 'household-objects',
    movies: 'movies-entertainment',
    sports: 'sports-games',
    nature: 'nature-geography',
  };
  const resolvedCategory = legacyCategories[category] ?? category;
  const shuffledIds = (ids: number[]): number[] => {
    for (let i = ids.length - 1; i > 0; i--) {
      const target = Math.floor(random() * (i + 1));
      [ids[i], ids[target]] = [ids[target], ids[i]];
    }
    return ids;
  };
  const categoryIds = category === 'random'
    ? []
    : wordPairs
      .filter((pair) => pair.category === resolvedCategory)
      .map((pair) => pair.id);
  if (categoryIds.length === 0) {
    return shuffledIds(wordPairs.map((pair) => pair.id));
  }

  const [preferredId, ...remainingCategoryIds] = shuffledIds(categoryIds);
  const otherIds = wordPairs
    .filter((pair) => pair.category !== resolvedCategory)
    .map((pair) => pair.id);
  return [
    preferredId,
    ...shuffledIds([...remainingCategoryIds, ...otherIds]),
  ];
}
